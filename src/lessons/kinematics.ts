function curve(id: string, label: string, expr: string, color: string, extra: Partial<AnimSeries> = {}): AnimSeries {
  return newSeries({ id, label, expr, color, ...extra })
}

/**
 * A moving object driven by formulas. `size` is given as a plain number and
 * turned into a flat size track, so it survives the expression mode.
 */
function body(patch: Omit<Partial<AnimLayer>, 'size'> & { exprX: string; size?: number }): AnimLayer {
  const { size, ...rest } = patch
  return newLayer({
    id: uid('layer'),
    mode: 'expr',
    exprY: '0',
    showTrail: false,
    showVelocity: false,
    showAcceleration: false,
    vectorScale: 10,
    ...rest,
    tracks: { size: size !== undefined ? [newKey(0, size), newKey(0.01, size)] : rest.tracks?.size },
  })
}

