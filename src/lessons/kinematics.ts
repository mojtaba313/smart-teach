const FULL = 'full' as const
const HALF = 'half' as const
const THIRD = 'third' as const

type Sp = SlideStep['span']

function step(kind: SlideStep['kind'], extra: Record<string, unknown>, span: Sp = FULL): SlideStep {
  return { id: uid('step'), span, kind, ...extra } as SlideStep
}

const t = (value: string, span: Sp = FULL) => step('text', { value }, span)
const formula = (value: string, span: Sp = FULL) => step('formula', { value }, span)
const list = (items: string[], span: Sp = FULL, ordered = false) => step('list', { items, ordered }, span)
const callout = (value: string, tone: 'info' | 'tip' | 'warn' | 'idea' = 'info', span: Sp = FULL) =>
  step('callout', { value, tone }, span)
const trap = (value: string, span: Sp = FULL) => step('trap', { value }, span)

